import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { createDemo } from '../src/lib/demo.ts';

const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
const errors = [], transmissions = [];
page.on('pageerror', e => errors.push(e.message));
page.on('request', r => { if (r.method() === 'POST' && !r.url().includes('__nextjs')) transmissions.push(r.url()); });
const fixture = async (index, name) => ({ name, mimeType: 'audio/wav', buffer: Buffer.from(await createDemo(index).arrayBuffer()) });
try {
  await page.goto(process.env.BASE_URL || 'http://127.0.0.1:3000', { waitUntil: 'networkidle' });
  const audio = [await fixture(0, '=mix.wav'), await fixture(1, 'Sunday sample.wav'), await fixture(2, 'New skies.wav')];
  await page.locator('input[type=file]').setInputFiles(audio);
  await page.waitForFunction(() => document.querySelectorAll('tbody .bpm-value').length === 3, null, { timeout: 120000 });
  const results = await page.locator('tbody tr').allInnerTexts();
  assert.match(results[0], /124/); assert.match(results[0], /A minor/);
  assert.match(results[1], /98/); assert.match(results[1], /C major/);
  assert.match(results[2], /128/); assert.match(results[2], /D minor/);
  await page.getByRole('button', { name: 'Play =mix', exact: true }).click();
  await page.getByRole('button', { name: 'Pause playback' }).waitFor();
  await page.getByRole('slider', { name: 'Playback position' }).fill('8');
  await page.getByRole('button', { name: 'Close player' }).click();
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV' }).click();
  const download = await downloadEvent;
  await download.saveAs(new URL('../artifacts/batch-results.csv', import.meta.url).pathname.replace(/^\/(\w:)/, '$1'));
  const csv = await readFile(new URL('../artifacts/batch-results.csv', import.meta.url), 'utf8');
  assert.ok(csv.includes('"\'=mix"'), 'Spreadsheet formulas must be escaped');
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.locator('tbody tr').count(), 0);
  assert.equal(await page.evaluate(() => localStorage.getItem('bpmfinder-results')), null);
  await page.locator('input[type=file]').setInputFiles([...audio, ...audio]);
  await page.getByRole('button', { name: 'Clear all', exact: true }).click();
  await page.waitForTimeout(1800);
  assert.equal(await page.locator('tbody tr').count(), 0, 'Cancelled files must not return to results');
  await page.locator('input[type=file]').setInputFiles([audio[0]]);
  await page.locator('tbody .bpm-value').waitFor();
  await page.getByRole('tab', { name: 'BPM & key finder' }).focus();
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.getByRole('tab', { name: 'Tap tempo' }).getAttribute('aria-selected'), 'true');
  await page.getByRole('button', { name: 'Privacy', exact: true }).click();
  await page.getByRole('button', { name: 'Close guide' }).focus();
  await page.keyboard.press('Shift+Tab');
  assert.equal(await page.evaluate(() => document.activeElement?.textContent), 'Back to the music ');
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(), 0);
  assert.equal(transmissions.length, 0); assert.equal(errors.length, 0, JSON.stringify(errors));
  const report = { results, transmissions, errors, checks: ['3-file batch using file input','all 3 tempo/key estimates','uploaded audio playback','seek','CSV formula escaping','3-result restore','cancel full batch','upload after cancellation','arrow-key tabs','modal focus trap'] };
  await writeFile(new URL('../artifacts/batch-check.json', import.meta.url), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} finally { await browser.close(); }
