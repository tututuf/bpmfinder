import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createDemo } from '../src/lib/demo.ts';
const production = process.argv.includes('--production');
const base = process.env.BASE_URL || 'http://127.0.0.1:3000';
await mkdir('artifacts/development-access', { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [], models = [];
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => { if (request.url().includes('/models/')) models.push(request.url()); });
try {
  await page.goto(base, { waitUntil: 'networkidle' });
  const status = await (await page.request.get(`${base}/api/billing/status`)).json();
  assert.equal(status.hasPro, false);
  assert.equal(status.developmentSavingUnlocked === true, !production);
  assert.equal(status.plan, null);
  assert.deepEqual(await (await page.request.get(`${base}/api/auth/session`)).json(), {});
  assert.equal(await page.getByRole('checkbox', { name: /Include danceability/ }).count(), 0);
  await page.locator('input[type=file]').setInputFiles({ name: 'Access check groove.wav', mimeType: 'audio/wav', buffer: Buffer.from(await createDemo(0).arrayBuffer()) });
  await page.locator('tbody .bpm-value').waitFor({ timeout: 120000 });
  assert.equal(await page.locator('tbody .bpm-value').textContent(), '124');
  assert.equal(await page.locator('tbody .metric-lock').count(), 3);
  assert.deepEqual(models, [], 'Free users never load insight models, including in development');
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV', exact: true }).click();
  const file = `artifacts/development-access/${production ? 'production' : 'development'}-free.csv`;
  await (await download).saveAs(file);
  assert.doesNotMatch(await readFile(file, 'utf8'), /Energy|Danceability|Happiness/);
  await page.getByRole('button', { name: 'View analysis of Access check groove', exact: true }).click();
  assert.equal(await page.locator('.insight-metric').count(), 0);
  assert.equal(await page.locator('.inspector-pro .locked-insights>span').count(), 3);
  await page.getByRole('button', { name: 'Close track details', exact: true }).click();
  await page.goto(`${base}/pricing`, { waitUntil: 'networkidle' });
  assert.equal(await page.getByText('All Pro features are unlocked.', { exact: true }).count(), 0);
  assert.equal(await page.getByRole('heading', { name: 'Save Results is unlocked for testing.', exact: true }).count(), production ? 0 : 1);
  assert.equal(await page.getByRole('link', { name: 'Sign in to upgrade', exact: true }).count(), 2);
  assert.deepEqual(errors, []);
  const report = { mode: production ? 'production' : 'development', guest: true, hasPro: status.hasPro, metricsLocked: true, noInsightModelRequests: true, csvDownload: true, developmentSavingUnlocked: status.developmentSavingUnlocked, errors };
  await writeFile(`artifacts/development-access/${report.mode}.json`, JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} finally { await browser.close(); }
