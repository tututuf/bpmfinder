import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createDemo } from '../src/lib/demo.ts';
const root = new URL('../', import.meta.url);
await mkdir(new URL('artifacts/', root), { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, acceptDownloads: true });
const page = await context.newPage();
const errors = [], requests = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
page.on('request', request => requests.push({ url: request.url(), method: request.method() }));
try {
  await page.goto(process.env.BASE_URL || 'http://127.0.0.1:3000', { waitUntil: 'networkidle' });
  await page.screenshot({ path: new URL('artifacts/preview.png', root).pathname.replace(/^\/(\w:)/, '$1'), fullPage: false });
  const mobilePreview = await context.newPage();
  await mobilePreview.setViewportSize({ width: 390, height: 844 });
  await mobilePreview.goto(process.env.BASE_URL || 'http://127.0.0.1:3000', { waitUntil: 'networkidle' });
  await mobilePreview.screenshot({ path: new URL('artifacts/mobile.png', root).pathname.replace(/^\/(\w:)/, '$1'), fullPage: true });
  await mobilePreview.close();
  await page.screenshot({ path: new URL('artifacts/desktop.png', root).pathname.replace(/^\/(\w:)/, '$1'), fullPage: true });
  assert.equal(await page.locator('tbody tr').count(), 0);
  await page.getByText('A clean slate. A new set.', { exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Play sample track' }).count(), 0);
  assert.equal(await page.getByRole('button', { name: /Try a demo/ }).count(), 0);
  assert.equal(await page.getByRole('button', { name: 'Export CSV', exact: true }).isDisabled(), true);
  assert.equal(await page.getByRole('button', { name: 'JSON', exact: true }).count(), 0);
  await page.getByRole('tab', { name: 'Tap tempo' }).click();
  for (let i = 0; i < 5; i++) { await page.getByRole('button', { name: 'Tap the beat' }).click(); await page.waitForTimeout(480); }
  const tapResult = await page.locator('.tempo-number').textContent();
  assert.match(tapResult, /\d/);
  await page.getByRole('tab', { name: 'Metronome' }).click();
  await page.getByRole('button', { name: 'Start metronome' }).click();
  await page.waitForTimeout(600);
  assert.equal(await page.locator('.beat-dots .on').count(), 1);
  await page.getByRole('button', { name: 'Stop metronome' }).click();
  await page.getByRole('tab', { name: 'BPM & key finder' }).click();
  const chooserEvent = page.waitForEvent('filechooser');
  await page.getByRole('button', { name: 'Choose your first track', exact: false }).click();
  await (await chooserEvent).setFiles({ name: 'My first track.wav', mimeType: 'audio/wav', buffer: Buffer.from(await createDemo(0).arrayBuffer()) });
  await page.locator('tbody tr .bpm-value').waitFor({ timeout: 120000 });
  const result = await page.locator('tbody tr').innerText();
  assert.match(result, /124|123|125/);
  assert.match(result, /minor/);
  await page.getByRole('button', { name: 'Play My first track', exact: true }).click();
  await page.getByRole('button', { name: 'Close player' }).waitFor();
  await page.getByRole('button', { name: 'Close player' }).click();
  await page.screenshot({ path: new URL('artifacts/analyzed.png', root).pathname.replace(/^\/(\w:)/, '$1'), fullPage: true });
  await page.getByRole('button', { name: /Options for/ }).click();
  const base = Number(await page.locator('tbody .bpm-value').textContent());
  await page.getByRole('button', { name: '½×', exact: true }).click();
  assert.equal(Number(await page.locator('tbody .bpm-value').textContent()), Math.round(base / 2 * 10) / 10);
  if (!await page.getByRole('button', { name: '2×', exact: true }).isVisible()) await page.getByRole('button', { name: /Options for/ }).click();
  await page.getByRole('button', { name: '2×', exact: true }).click();
  const downloads = [];
  page.on('download', download => downloads.push(download));
  assert.doesNotMatch(await page.getByRole('button', { name: 'Export CSV' }).innerText(), /PRO/);
  const freeDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV' }).click();
  await (await freeDownload).saveAs(new URL('artifacts/browser-free.csv', root).pathname.replace(/^\/(\w:)/, '$1'));
  assert.equal(downloads.length, 1);
  assert.match(await readFile(new URL('artifacts/browser-free.csv', root), 'utf8'), /My first track/);
  assert.equal(await page.evaluate(() => localStorage.getItem('bpmfinder-results')), null, 'Analysis and edits do not persist results');
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.locator('tbody tr').count(), 0, 'Refresh clears analyzed results');
  assert.equal(await page.getByRole('button', { name: 'Close player' }).count(), 0);
  await page.getByText('A clean slate. A new set.').waitFor();
  await page.locator('input[type=file]').setInputFiles({ name: 'not-audio.txt', mimeType: 'text/plain', buffer: Buffer.from('test') });
  await page.getByRole('status').filter({ hasText: 'Choose an audio file' }).waitFor();
  await page.locator('input[type=file]').setInputFiles({ name: 'broken.wav', mimeType: 'audio/wav', buffer: Buffer.from('not a wav') });
  await page.getByText('This audio format could not be read. Try a WAV or MP3 file.').first().waitFor();
  await page.getByRole('button', { name: 'Clear all', exact: true }).click();
  await page.getByRole('button', { name: 'Privacy', exact: true }).click();
  await page.getByRole('dialog').waitFor();
  await page.getByText('Refreshing or closing the page clears them.', { exact: false }).waitFor();
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(), 0);
  await page.evaluate(() => {
    localStorage.setItem('bpmfinder-results', JSON.stringify([{ id: 'old-track', name: 'Old recording', duration: 32, bpm: 120, key: 'C major', camelot: '8B', waveform: [] }]));
    localStorage.setItem('unrelated-setting', 'keep');
  });
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.locator('tbody tr').count(), 0, 'Old history is not restored');
  assert.equal(await page.evaluate(() => localStorage.getItem('bpmfinder-results')), null, 'Old result storage is removed');
  assert.equal(await page.evaluate(() => localStorage.getItem('unrelated-setting')), 'keep', 'Cleanup is scoped to app results');
  await page.evaluate(() => localStorage.removeItem('unrelated-setting'));
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.locator('tbody tr').count(), 0, 'Clearing and reloading keeps the workspace empty');
  for (const width of [375, 390, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 950 });
    await page.evaluate(() => window.scrollTo(0, 0));
    const sizes = await page.evaluate(() => ({ screen: innerWidth, body: document.documentElement.scrollWidth }));
    assert.ok(sizes.body <= sizes.screen, `Horizontal overflow at ${width}: ${JSON.stringify(sizes)}`);
    await page.screenshot({ path: new URL(`artifacts/viewport-${width}.png`, root).pathname.replace(/^\/(\w:)/, '$1'), fullPage: true });
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Toggle navigation' }).click();
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Blogs', exact: true }).click();
  await page.waitForURL('**/blogs');
  assert.equal(await page.getByRole('heading', { level: 1 }).count(), 1);
  assert.equal(await page.locator('.site-header .nav a[href="/blogs"]').getAttribute('aria-current'), 'page');
  for (const width of [375, 768, 1440]) {
    await page.setViewportSize({ width, height: 950 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Blogs overflow');
    if (width !== 768) await page.screenshot({ path: new URL('artifacts/blogs-' + width + '.png', root).pathname.replace(/^\/(\w:)/, '$1'), fullPage: true });
  }
  await page.getByRole('link', { name: 'Back to the audio tools' }).click();
  await page.waitForURL('**/#workspace');
  const summary = { tapResult, analyzedTrack: result, errors, externalRequests: requests.filter(r => !r.url.startsWith(new URL(process.env.BASE_URL || 'http://127.0.0.1:3000').origin + '/') && !r.url.startsWith('blob:') && !r.url.startsWith('data:')), requests: requests.length, checks: ['desktop layout','uploaded audio playback','tap tempo','metronome','empty initial workspace', 'no demo entry points', 'upload from empty state', 'uploaded audio analysis', 'legacy storage removed; unrelated settings retained','tempo corrections','CSV downloads freely without a Pro badge','refresh clears results','clear results','invalid file','decode failure','privacy dialog','mobile navigation','overflow at 375,390,768,1024,1440'] };
  assert.equal(errors.length, 0, JSON.stringify(errors));
  await writeFile(new URL('artifacts/browser-check.json', root), JSON.stringify(summary, null, 2));
  console.log(JSON.stringify(summary, null, 2));
} catch (error) {
  await page.screenshot({ path: new URL('artifacts/failure.png', root).pathname.replace(/^\/(\w:)/, '$1'), fullPage: true });
  console.error(JSON.stringify({ errors, page: await page.locator('body').innerText() }, null, 2));
  throw error;
} finally { await browser.close(); }
